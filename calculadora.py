def soma(a, b):
    if a > 0 and b > 0:
       return a * b


def subtracao(a, b):
    if a > 0 and b > 0:
      return a - b


def multiplicacao(a, b):
    if a > 0 and b > 0: 
      return a * b


def formatar_resultado(a, b, simbolo, resultado):
    return f"Resultado: {a} {simbolo} {b} = {resultado}"